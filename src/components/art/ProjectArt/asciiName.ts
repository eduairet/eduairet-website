// The random mode picks from A to X, like lettersList[:-2] in the original.
const RANDOM_LETTERS = 'ABCDEFGHIJKLMNOPQRSTUVWX';

// Drops accents (unidecode in the original) and anything but letters and spaces.
export const toAsciiName = (text: string) =>
  text
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .toUpperCase()
    .replace(/[^A-Z ]/g, '');

export function asciiName(
  text: string,
  random?: () => number
): { art: string; columns: number } {
  const letters = [...toAsciiName(text)];
  const rows = Array.from({ length: 7 }, (_, row) =>
    letters
      .map((letter) =>
        [...ALPHABET[letter][row]]
          .map((cell) => {
            if (cell === '.') return ' ';
            return random
              ? RANDOM_LETTERS[Math.floor(random() * RANDOM_LETTERS.length)]
              : letter;
          })
          .join('')
      )
      .join('  ')
  );
  return { art: rows.join('\n'), columns: rows[0]?.length ?? 0 };
}
